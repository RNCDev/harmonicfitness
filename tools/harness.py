"""The two assistants sweatcast runs under: Claude Code and ChatGPT's Codex.

Claude Code's files are the source: CLAUDE.md, .claude/skills/<name>/SKILL.md and .claude/settings.json.
Codex reads AGENTS.md and .agents/skills/ instead, so those are generated here: AGENTS.md sends Codex to
CLAUDE.md, with what to use in place of Claude Code's own tools, and .agents/skills/<name>/ is an exact copy
of .claude/skills/<name>/ (the ChatGPT app's own import of Claude skills makes the same copy, so it changes
nothing).
.codex/config.toml (network on) and .codex/rules/sweatcast.rules (./sweatcast runs outside Codex's
sandbox, as .claude/settings.json allows it in Claude Code) are written by hand; check makes sure the
rule and the allow list still name the same command.

    ./sweatcast harness          # check: exit 1 and a list when the Codex files are out of step
    ./sweatcast harness sync     # rewrite AGENTS.md and .agents/skills/ from the Claude files
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import cli  # noqa: E402
import errors  # noqa: E402
import paths  # noqa: E402

CLAUDE_SKILLS = os.path.join(".claude", "skills")
CODEX_SKILLS = os.path.join(".agents", "skills")
AGENTS = "AGENTS.md"
CODEX_RULES = ".codex/rules/sweatcast.rules"   # forward slashes: it's quoted in AGENTS.md on every system
CODEX_CONFIG = os.path.join(".codex", "config.toml")
SETTINGS = os.path.join(".claude", "settings.json")
GENERATED = "Generated by `./sweatcast harness sync` from the Claude Code files; edit those, then sync."


def skills(root):
    """The Claude skills, by name, each with its frontmatter block (between the --- lines)."""
    folder = os.path.join(root, CLAUDE_SKILLS)
    found = {}
    for name in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
        path = os.path.join(folder, name, "SKILL.md")
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as f:
            text = f.read()
        parts = text.split("---\n", 2)
        if not text.startswith("---\n") or len(parts) < 3:
            raise errors.SweatcastError(f"{path}: no frontmatter between --- lines.")
        found[name] = parts[1]
    return found


def agents_md(names):
    listed = "\n".join(f"- `{n}`: `.claude/skills/{n}/SKILL.md`" for n in names)
    return f"""# sweatcast: instructions for ChatGPT's Codex

<!-- {GENERATED} -->

Read `CLAUDE.md` in full before doing anything else, and follow it as your own instructions: it's written for Claude Code and kept for both assistants, and where it says "Claude", it means you.

The skills, copied whole into `.agents/skills/`:
{listed}

Where the instructions name a Claude Code tool, use the nearest one you have:
- **AskUserQuestion:** the same question and options, as a multiple-choice question if you can, else a short numbered list; wait for the answer.
- **SendUserFile:** run `./sweatcast show "<file>"` (it opens the file's folder with the file selected) and give the path.
- **Agent with `run_in_background`** (the research agents): do that research yourself, within the same budgets, before the step that needs it.
- **`run_in_background` on a command:** run it and wait.
- **Artifact:** not available here; skip that step.

Rules that always hold:
- Never read, print or copy `me/.env`, not even through a search over a folder: it holds the listener's voice keys.
- Run sweatcast's tools only as `./sweatcast <command>` from this folder. This project's rule (`{CODEX_RULES}`) runs them outside the sandbox, since they need downloads, the Mac's GPU for a local voice, git's settings for the privacy hook, and `me/.env` for a web coach's key (sweatcast reads it; you never do). If one fails with "Operation not permitted" or a GPU message, run it again outside the sandbox.
- During a session, write only inside `me/`.
- Once, before the first workout, say plainly: ChatGPT may use what it reads here, including the listener's health notes, to improve its models unless "Improve the model for everyone" is off (Settings, Data Controls).
"""


def expected(root):
    """Every generated file's path (relative to root) and the text it should hold."""
    found = skills(root)
    files = {AGENTS: agents_md(list(found)).encode("utf-8")}
    for name in found:
        src = os.path.join(root, CLAUDE_SKILLS, name)
        for dirpath, _, filenames in os.walk(src):
            for fn in filenames:
                if fn == ".DS_Store":
                    continue
                rel = os.path.relpath(os.path.join(dirpath, fn), src)
                files[os.path.join(CODEX_SKILLS, name, rel)] = _read(os.path.join(dirpath, fn))
    return files


def _extras(root, want):
    """Files under .agents/skills/ that no Claude skill file accounts for."""
    folder = os.path.join(root, CODEX_SKILLS)
    out = []
    for dirpath, _, filenames in os.walk(folder):
        for fn in filenames:
            rel = os.path.relpath(os.path.join(dirpath, fn), root)
            if fn != ".DS_Store" and rel not in want:
                out.append(rel)
    return sorted(out)


def _read(path):
    """The file's bytes (a skill may hold an image as well as text), or None when it isn't there."""
    try:
        with open(path, "rb") as f:
            return f.read()
    except OSError:
        return None


ENV_DENIES = ("Read(/me/.env)", "Edit(/me/.env)", "Write(/me/.env)")


def problems(root=None):
    """What's out of step between the two assistants' files, as lines; empty when they agree."""
    root = root or paths.ROOT
    out = []
    want = expected(root)
    for rel, text in want.items():
        have = _read(os.path.join(root, rel))
        if have is None:
            out.append(f"{rel}: missing")
        elif have != text:
            out.append(f"{rel}: out of step with the Claude Code files")
    for rel in _extras(root, want):
        out.append(f"{rel}: no Claude skill file of that name any more")
    rules = (_read(os.path.join(root, CODEX_RULES)) or b"").decode("utf-8", "replace")
    if '"./sweatcast"' not in rules:
        out.append(f"{CODEX_RULES}: should allow [\"./sweatcast\"], as {SETTINGS} does")
    try:
        with open(os.path.join(root, SETTINGS), encoding="utf-8") as f:
            permissions = json.load(f).get("permissions", {})
    except (OSError, ValueError):
        permissions = {}
    if "Bash(./sweatcast:*)" not in permissions.get("allow", []):
        out.append(f"{SETTINGS}: should allow Bash(./sweatcast:*), as {CODEX_RULES} does")
    for rule in ENV_DENIES:
        if rule not in permissions.get("deny", []):
            out.append(f"{SETTINGS}: should deny {rule} (the listener's voice keys)")
    if "network_access = true" not in (_read(os.path.join(root, CODEX_CONFIG)) or b"").decode("utf-8", "replace"):
        out.append(f"{CODEX_CONFIG}: should turn on network access for the sandbox")
    return out


def sync(root=None):
    """Rewrite the generated files; returns the paths changed."""
    root = root or paths.ROOT
    changed = []
    want = expected(root)
    for rel, text in want.items():
        path = os.path.join(root, rel)
        if _read(path) != text:
            os.makedirs(os.path.dirname(path) or root, exist_ok=True)
            with open(path, "wb") as f:
                f.write(text)
            changed.append(rel)
    for rel in _extras(root, want):
        os.remove(os.path.join(root, rel))
        changed.append(f"{rel} (removed)")
    folder = os.path.join(root, CODEX_SKILLS)
    for dirpath, dirnames, filenames in os.walk(folder, topdown=False):   # children first, so parents empty out
        if dirpath != folder and not os.listdir(dirpath):
            os.rmdir(dirpath)
    return changed


def main(argv=None):
    ap = cli.ArgumentParser(prog="sweatcast harness",
                            description="Keep ChatGPT's Codex files in step with the Claude Code ones.")
    ap.add_argument("action", nargs="?", choices=["check", "sync"], default="check")
    a = ap.parse_args(argv)
    if a.action == "sync":
        changed = sync()
        print("\n".join(f"wrote {c}" for c in changed) or "Already in step.")
        left = problems()
        if left:
            print("\n".join(left), file=sys.stderr)
            return cli.ISSUES
        return cli.OK
    left = problems()
    if left:
        print("\n".join(left) + "\nRun ./sweatcast harness sync (the rule and settings lines are edited by hand).",
              file=sys.stderr)
        return cli.ISSUES
    print("Claude Code and Codex files are in step.")
    return cli.OK


if __name__ == "__main__":
    sys.exit(cli.run(main))
